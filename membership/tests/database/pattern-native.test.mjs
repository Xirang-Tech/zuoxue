import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import pg from 'pg';
import { Database } from '../../server/database.mjs';
import { migrate } from '../../scripts/migrate.mjs';
import { MembershipService } from '../../server/service.mjs';
import { PRODUCT_IDS, assignVariant } from '../../shared/domain.mjs';
const connection=process.env.TEST_DATABASE_URL, source=process.env.PATTERN_SOURCE_ROOT;
test('central paid order installs consumable pattern quotas, then restores its original native plan', {skip:!connection||!source}, async t => {
  assert(['localhost','127.0.0.1'].includes(new URL(connection).hostname));
  const root=new pg.Pool({connectionString:connection});
  const schema=`union_pattern_${randomUUID().replaceAll('-','')}`;
  await root.query(`CREATE SCHEMA ${schema}`);
  const url=new URL(connection);url.searchParams.set('options',`-c search_path=${schema}`);
  const db=new Database(url.href);await migrate(db);
  process.env.DATABASE_URL=url.href;
  const load=relative=>import(pathToFileURL(`${source}/${relative}`).href);
  const nativeDb=await load('server/db.js');const pool=await nativeDb.initDb();
  t.after(async()=>{await pool.end();await db.close();await root.query(`DROP SCHEMA ${schema} CASCADE`);await root.end();});
  const {createPatternAdapter}=await load('server/union/native.js');
  const {PgCommerceAdapter,grantAdminEntitlement}=await load('server/commercePg.js');
  const {SKU}=await load('shared/commerceCatalog.js');
  let now=Date.now();const adapter=createPatternAdapter({verified:true,now:()=>now});
  const catalog=JSON.parse(await readFile(new URL('../../config/catalog.json',import.meta.url),'utf8'));
  catalog.approved=true;catalog.costApproved=true;catalog.version='native-integration-only';
  catalog.plans[0].priceCents=14900;catalog.plans[1].priceCents=129900;
  for(const p of catalog.products){p.verified=true;if(p.id!=='pattern') p.grants={monthly:[{unit:'test-credit',amount:1,schedule:'monthly'}],yearly:[{unit:'test-credit',amount:1,schedule:'monthly'}]};}
  let user='native-pattern-test-0';for(let i=0;assignVariant(user,'native-test','test-salt')!=='B';i++)user=`native-pattern-test-${i+1}`;
  await adapter.execute('snapshot',{centralUserId:user});
  const local=(await db.query('SELECT id FROM users WHERE central_user_id=$1',[user])).rows[0];
  await grantAdminEntitlement(local.id,{skuId:SKU.PRO_30});
  const commerce=new PgCommerceAdapter(), before=await commerce.summary(local.id);
  const adapters={configured:()=>true,snapshots:async uid=>Object.fromEntries(await Promise.all(PRODUCT_IDS.map(async id=>[id,id==='pattern'?await adapter.execute('snapshot',{centralUserId:uid}):{ready:true,tierId:'free',tierRank:0,remainingMs:0,autoRenewActive:false,pendingReservations:0,pendingSubscriptionOrder:false}]))),call:async(id,action,body)=>id==='pattern'?adapter.execute(action,body):{ok:true}};
  const service=new MembershipService({db,catalog,adapters,payments:{ready:()=>true},config:{version:'native-test',salt:'test-salt',experimentEnabled:true,salesEnabled:true},now:()=>now});
  await service.enroll(user,'pattern',{baselineStatus:'pro'});
  const quote=await service.quote(user,'monthly');
  const order=await service.createOrder(user,quote.id,randomUUID(),{productId:'pattern',entry:'paywall'});
  await service.acceptPayment({orderId:order.id,transactionId:'test-only-payment',amountCents:order.amount_cents,currency:'CNY',paidAt:now});
  await service.runWorker();
  assert.equal((await service.status(user)).status,'active');
  let state=await commerce.summary(local.id);assert.equal(state.plan.source,'union');assert.equal(state.planCredits,3);assert.equal(state.toolQuota.remaining,30);
  await commerce.unlockProject(local.id,'native-e2e-project');
  const reservation=await commerce.reserve(local.id,{scope:'tool',feature:'chat'});await commerce.attachReservation(local.id,reservation.id);await commerce.settleReservation(local.id,reservation.id,{success:true});
  state=await commerce.summary(local.id);assert.equal(state.planCredits,2);assert.equal(state.toolQuota.remaining,29);
  now+=40*86400000;await service.runWorker();
  assert.equal((await service.status(user)).status,'expired');
  state=await commerce.summary(local.id);assert.equal(state.plan.source,'admin');assert.equal(state.planCredits,before.planCredits);assert.equal(state.toolQuota.remaining,before.toolQuota.remaining);assert(state.unlockedProjects['native-e2e-project']);
});
